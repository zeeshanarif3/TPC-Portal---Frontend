const Student = require('../models/Student');
const Course = require('../models/Course');
const College = require('../models/College');
const Slot = require('../models/Slot');
const User = require('../models/User');
const bcrypt = require('bcryptjs');

// Create a new student
exports.createStudent = async (req, res) => {
  const { email } = req.body;
  try {
    const { rollNumber, name, courseId, dob } = req.body;
    const userId = req.user.id;
    const userRole = req.user.role;

    if (!email || !dob) {
      return res.status(400).json({ message: 'Email and date of birth (dob) are required' });
    }

    // Check if user already exists
    const existingUser = await User.findOne({ email });
    if (existingUser) {
      return res.status(400).json({ message: 'A user with this email already exists' });
    }

    // If moderator, verify they are associated with the college
    let moderatorCollege = null;
    if (userRole === 'moderator') {
      moderatorCollege = await College.findOne({ moderatorId: userId });
      if (!moderatorCollege) {
        return res.status(404).json({ message: 'College not found for this moderator' });
      }
    }

    // Verify that the course exists
    const course = await Course.findById(courseId);
    if (!course) {
      return res.status(400).json({ message: 'Course not found' });
    }

    // If moderator, verify the course belongs to their college
    if (userRole === 'moderator') {
      if (!moderatorCollege) {
        return res.status(404).json({ message: 'College not found for this moderator' });
      }
      if (course.collegeId.toString() !== moderatorCollege._id.toString()) {
        return res.status(403).json({ message: 'Moderators can only create students for courses in their own college' });
      }
    }

    // Create Student profile. User account is autogenerated via pre-save hook in Student model.
    const student = new Student({ 
      rollNumber, 
      name, 
      email, 
      dob: new Date(dob),
      courseId
    });
    await student.save();

    // Determine raw password to send back to frontend
    let rawPassword;
    if (typeof dob === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(dob.split('T')[0])) {
      rawPassword = dob.split('T')[0].replace(/-/g, '');
    } else {
      const dateObj = new Date(dob);
      const yyyy = dateObj.getUTCFullYear();
      const mm = String(dateObj.getUTCMonth() + 1).padStart(2, '0');
      const dd = String(dateObj.getUTCDate()).padStart(2, '0');
      rawPassword = `${yyyy}${mm}${dd}`;
    }

    res.status(201).json({ student, userPassword: rawPassword });
  } catch (error) {
    // Cleanup orphaned user account if student save failed after user was saved in pre-save hook
    if (email) {
      try {
        const orphanedUser = await User.findOne({ email, role: 'student' });
        if (orphanedUser) {
          const studentExists = await Student.findOne({ userId: orphanedUser._id });
          if (!studentExists) {
            await User.findByIdAndDelete(orphanedUser._id);
          }
        }
      } catch (cleanupErr) {
        console.error('Failed to cleanup orphaned user:', cleanupErr);
      }
    }
    if (error.code === 11000) {
      return res.status(400).json({ message: 'Student with this roll number already exists in the course' });
    }
    res.status(500).json({ message: error.message });
  }
};

// Get all students
exports.getAllStudents = async (req, res) => {
  try {
    const userId = req.user.id;
    const userRole = req.user.role;

    let filter = {};
    if (userRole === 'moderator') {
      const moderatorCollege = await College.findOne({ moderatorId: userId });
      if (!moderatorCollege) {
        return res.status(404).json({ message: 'College not found for this moderator' });
      }
      // Get courses for this college, then students in those courses
      const courses = await Course.find({ collegeId: moderatorCollege._id });
      const courseIds = courses.map(c => c._id);
      filter = { courseId: { $in: courseIds } };
    }

    const students = await Student.find(filter).populate('courseId', 'courseCode');
    res.status(200).json(students);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

