// Get attendance for currently logged-in student
exports.getMyAttendance = async (req, res) => {
  try {
    const userId = req.user.id;
    const userRole = req.user.role;

    if (userRole !== 'student') {
      return res.status(403).json({ message: 'Access denied: Only students can access this route' });
    }

    // 1. Find the student profile using userId
    const student = await Student.findOne({ userId });
    if (!student) {
      return res.status(404).json({ message: 'Student profile not found for this user' });
    }

    // 2. Find all completed/attendance-taken slots for the student's course
    const slots = await Slot.find({
      courseId: student.courseId,
      attendanceTaken: true
    }).populate('trainerId', 'name').sort({ date: 1, startTime: 1 });

    // 3. Process attendance history
    const attendanceRecords = slots.map(slot => {
      const isPresent = slot.presentStudents.includes(student.rollNumber);
      return {
        slotId: slot._id,
        date: slot.date,
        startTime: slot.startTime,
        endTime: slot.endTime,
        topic: slot.topic || 'N/A',
        roomNo: slot.roomNo,
        trainerName: slot.trainerId ? slot.trainerId.name : 'N/A',
        present: isPresent
      };
    });

    // 4. Calculate summary stats
    const totalClasses = attendanceRecords.length;
    const attendedClasses = attendanceRecords.filter(r => r.present).length;
    const absentClasses = totalClasses - attendedClasses;
    const attendancePercentage = totalClasses > 0 ? parseFloat(((attendedClasses / totalClasses) * 100).toFixed(2)) : 0;

    res.status(200).json({
      student: {
        id: student._id,
        name: student.name,
        rollNumber: student.rollNumber,
        courseId: student.courseId
      },
      summary: {
        totalClasses,
        attendedClasses,
        absentClasses,
        attendancePercentage
      },
      records: attendanceRecords
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
